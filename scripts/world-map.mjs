/**
 * Writes src/webview/worldmap.js, the land outline the Endpoints panel draws
 * GeoIP locations on: world-atlas's land-110m (Natural Earth, public domain;
 * the package is ISC) as one SVG path in an equirectangular projection (x =
 * longitude + 180, y = 90 − latitude, a tenth of a degree), so the webview
 * needs no network and no projection code.
 *
 *   node scripts/world-map.mjs   (pnpm run worldmap; `make update` runs it)
 *
 * test/scripts/worldmap.test.mjs fails while the file differs from what this
 * writes from the installed package.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = join(ROOT, "node_modules", "world-atlas", "land-110m.json");
export const TARGET = join(ROOT, "src", "webview", "worldmap.js");

/** The arcs of a TopoJSON topology as [longitude, latitude] points. */
function decodeArcs(topology) {
  const [sx, sy] = topology.transform.scale;
  const [tx, ty] = topology.transform.translate;
  return topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

/** A ring's points from its arc indexes (~i: arc i reversed), without repeated joints. */
function ring(arcs, indexes) {
  const points = [];
  for (const i of indexes) {
    const arc = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

/** The SVG path of every ring: absolute start, relative steps, in tenths of a degree. */
export function landPath(topology) {
  const arcs = decodeArcs(topology);
  const polygons = [];
  for (const geometry of topology.objects.land.geometries) {
    if (geometry.type === "Polygon") {
      polygons.push(geometry.arcs);
    } else if (geometry.type === "MultiPolygon") {
      polygons.push(...geometry.arcs);
    }
  }
  const parts = [];
  for (const polygon of polygons) {
    for (const indexes of polygon) {
      // A ring crossing the antimeridian jumps from -180° to 180°: unwrap it
      // (no step longer than half the world), and where it then runs past an
      // edge, draw a copy shifted by 360° too (the map's viewBox clips both).
      let shift = 0;
      let last = null;
      const points = ring(arcs, indexes).map(([lon, lat]) => {
        if (last !== null && Math.abs(lon + shift - last) > 180) {
          shift += lon + shift > last ? -360 : 360;
        }
        last = lon + shift;
        return [Math.round((last + 180) * 10), Math.round((90 - lat) * 10)];
      });
      const xs = points.map(([x]) => x);
      const offsets = [0];
      if (Math.min(...xs) < 0) {
        offsets.push(3600);
      }
      if (Math.max(...xs) > 3600) {
        offsets.push(-3600);
      }
      for (const offset of offsets) {
        let [px, py] = points[0];
        let d = `M${(px + offset) / 10} ${py / 10}`;
        for (const [x, y] of points.slice(1)) {
          if (x !== px || y !== py) {
            d += `l${(x - px) / 10} ${(y - py) / 10}`;
            [px, py] = [x, y];
          }
        }
        parts.push(`${d}z`);
      }
    }
  }
  return parts.join("");
}

export function worldMapScript(topology) {
  return [
    "// Generated by scripts/world-map.mjs from world-atlas's land-110m (Natural",
    "// Earth, public domain): do not edit. x = longitude + 180, y = 90 - latitude.",
    `window.PcapWorldMap = { width: 360, height: 180, land: ${JSON.stringify(landPath(topology))} };`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const script = worldMapScript(JSON.parse(readFileSync(SOURCE, "utf8")));
  writeFileSync(TARGET, script);
  console.log(`Wrote ${TARGET} (${script.length.toLocaleString()} bytes)`);
}
